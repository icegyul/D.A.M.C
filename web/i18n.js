export const DICTIONARIES = { en: EN, ko: KO };

let current = DEFAULT_LANGUAGE;

/** Pick a starting language from the browser, when one is available. */
export function detectLanguage(navigatorLanguage) {
  const raw = String(navigatorLanguage ?? '').toLowerCase();
  return raw.startsWith('ko') ? 'ko' : DEFAULT_LANGUAGE;
}

export function isSupported(lang) {
  return Object.prototype.hasOwnProperty.call(DICTIONARIES, lang);
}

export function setLanguage(lang) {
  current = isSupported(lang) ? lang : DEFAULT_LANGUAGE;
  return current;
}

export function getLanguage() {
  return current;
}

function interpolate(template, params) {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, key) =>
    Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : match);
}

/** Pure lookup, used by tests and by t(). Falls back to English, then the key. */
export function translate(lang, key, params) {
  const dict = DICTIONARIES[lang] ?? EN;
  const template = dict[key] ?? EN[key] ?? key;
  return interpolate(template, params);
}

export function t(key, params) {
  return translate(current, key, params);
}
